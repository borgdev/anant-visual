import { execFileSync, spawn, type ChildProcess } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium, firefox, webkit, type Browser, type BrowserContext, type Page } from "playwright-core";
import { afterAll, beforeAll, describe, expect, test } from "vitest";

/**
 * The library as a site uses it: packed, installed into a Next 16 + Tailwind 4 app, built,
 * served and driven by a real browser. What the unit tests can only check as strings (motion
 * that plays, hover that dims, a viewer that zooms, text that fits its box) is checked here
 * as the browser actually does it.
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const app = fileURLToPath(new URL("./next-app/", import.meta.url));
const PORT = 4173;
const URL_ = `http://localhost:${PORT}/`;
const axeSource = readFileSync(fileURLToPath(new URL("../node_modules/axe-core/axe.min.js", import.meta.url)), "utf8");

let server: ChildProcess;
let browser: Browser;

const run = (cmd: string, args: string[], cwd: string) => execFileSync(cmd, args, { cwd, stdio: "pipe", timeout: 300_000 });

beforeAll(async () => {
  // Regenerate the samples the app renders, so it always shows what the gallery shows.
  const data = execFileSync("node", ["-e", 'import("./scripts/samples.mjs").then(m=>console.log(JSON.stringify(m.samples.map(s=>({id:s.spec.id,spec:s.spec})))))'], { cwd: root }).toString();
  const samples = JSON.parse(data);
  const ids = Array.from({ length: 10 }, (_, i) => `n${i}`);
  samples.push({
    id: "technical-big",
    spec: {
      id: "technical-big", label: "A technical diagram", profile: "technical", motion: ["reveal"],
      caption: "A caption long enough to state the concept the figure makes, as the contract requires of every figure.",
      nodes: ids.map((id) => ({ id, label: id.toUpperCase() })),
      edges: ids.slice(1).map((id, i) => ({ from: ids[i], to: id })),
    },
  });
  const { writeFileSync } = await import("node:fs");
  writeFileSync(`${app}app/samples.ts`, `// Generated by e2e/browser.test.ts; do not edit.\nimport type { FigureInput } from "@anant/visual/core";\n\nexport const samples: { id: string; spec: FigureInput }[] = ${JSON.stringify(samples, null, 1)} as never;\n`);

  run("npm", ["run", "build"], root);
  const tarball = run("npm", ["pack", "--silent"], root).toString().trim().split("\n").pop()!;
  run("npm", ["install", "--no-audit", "--no-fund", `${root}${tarball}`], app);
  run("npx", ["next", "build"], app);
  server = spawn("npx", ["next", "start", "-p", String(PORT)], { cwd: app, stdio: "pipe" });
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(URL_)).ok) break;
    } catch { /* not up yet */ }
    await new Promise((r) => setTimeout(r, 500));
  }
  // BROWSER=chrome (default), firefox or webkit. `npm run test:browser:all` runs all three.
  const which = process.env.BROWSER ?? "chrome";
  browser = which === "firefox" ? await firefox.launch() : which === "webkit" ? await webkit.launch() : await chromium.launch({ channel: "chrome", headless: true });
});

afterAll(async () => {
  await browser?.close();
  server?.kill();
});

const open = async (opts: { reducedMotion?: "reduce" | "no-preference"; width?: number; dark?: boolean } = {}) => {
  const context: BrowserContext = await browser.newContext({ viewport: { width: opts.width ?? 1280, height: 900 }, reducedMotion: opts.reducedMotion ?? "no-preference" });
  const page = await context.newPage();
  const errors: string[] = [];
  // A missing favicon is the host app's, not the library's; any other failed request or console error is a defect.
  page.on("console", (m) => m.type() === "error" && !m.text().startsWith("Failed to load resource") && errors.push(m.text()));
  page.on("response", (r) => r.status() >= 400 && !r.url().endsWith("/favicon.ico") && errors.push(`${r.status()} ${r.url()}`));
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(URL_, { waitUntil: "networkidle" });
  if (opts.dark) await page.evaluate(() => document.documentElement.classList.add("dark"));
  return { page, context, errors };
};

const opacityOf = (page: Page, selector: string) =>
  page.evaluate((s) => Number(getComputedStyle(document.querySelector(s)!).opacity), selector);

describe("the page", () => {
  test("hydrates without errors and draws every figure as one SVG", async () => {
    const { page, context, errors } = await open();
    expect(errors).toEqual([]);
    const figures = await page.locator("section[data-sample]").count();
    expect(figures).toBeGreaterThanOrEqual(15);
    expect(await page.locator("section[data-sample] svg").count()).toBeGreaterThanOrEqual(figures);
    await context.close();
  });

  test("every word fits inside the node it labels", async () => {
    const { page, context } = await open();
    const overflows = await page.evaluate(() => {
      const bad: string[] = [];
      // A matrix dot, a network node and a chart category carry their words beside the mark, not inside it.
      const beside = new Set(["mx", "nw", "stages", "latency"]);
      document.querySelectorAll("svg g.node[data-id]").forEach((g) => {
        if (beside.has(g.closest("section")?.getAttribute("data-sample") ?? "")) return;
        // The first filled shape is the node's outline (a sequence participant starts with its lifeline, which is not).
        const outline = [...g.querySelectorAll("rect, path")].find((e) => getComputedStyle(e).fill !== "none") as SVGGraphicsElement | undefined;
        if (!outline) return;
        const box = outline.getBBox();
        g.querySelectorAll("text").forEach((t) => {
          const b = (t as SVGGraphicsElement).getBBox();
          // A rotated label (a lane header) is measured in its own frame, so only upright text is checked.
          if (t.getAttribute("transform")) return;
          if (b.x < box.x - 2 || b.x + b.width > box.x + box.width + 2 || b.y < box.y - 2 || b.y + b.height > box.y + box.height + 2) {
            bad.push(`${g.closest("section")?.getAttribute("data-sample")}:${g.getAttribute("data-id")}:${t.textContent}`);
          }
        });
      });
      return bad;
    });
    expect(overflows).toEqual([]);
    await context.close();
  });

  test("no page-wide horizontal scroll at phone width, and a diagram becomes its list", async () => {
    const { page, context } = await open({ width: 375 });
    expect(await page.evaluate(() => document.scrollingElement!.scrollWidth <= window.innerWidth)).toBe(true);
    const wide = page.locator('section[data-sample="review-path"]');
    expect(await wide.locator("ol").first().isVisible()).toBe(true);
    expect(await wide.locator("svg").first().isVisible()).toBe(false);
    await context.close();
  });
});

describe("motion", () => {
  test("a figure is complete until it is armed, then plays once when it scrolls into view", async () => {
    const { page, context } = await open();
    // Far down the page, so it is out of view when armed.
    const svg = 'section[data-sample="ortho"] svg';
    await page.waitForFunction((s) => document.querySelector(s)?.hasAttribute("data-armed"), svg);
    // Armed and out of view: the animated parts wait, dimmed.
    expect(await opacityOf(page, `${svg} g.node`)).toBe(0);
    expect(await page.evaluate((s) => document.querySelector(s)!.hasAttribute("data-play"), svg)).toBe(false);

    await page.locator('section[data-sample="ortho"]').scrollIntoViewIfNeeded();
    await page.waitForFunction((s) => document.querySelector(s)!.hasAttribute("data-play"), svg);
    const names = await page.evaluate(() => document.getAnimations().map((a) => (a as CSSAnimation).animationName));
    expect(names).toContain("av-reveal");
    expect(names).toContain("av-trace");

    // Everything ends up visible, and the pulse runs along the edge afterwards.
    await page.waitForTimeout(4200);
    expect(await opacityOf(page, `${svg} g.node`)).toBe(1);
    expect(await page.evaluate((s) => [...document.querySelectorAll(`${s} g.edge`)].every((e) => Number(getComputedStyle(e).opacity) === 1), svg)).toBe(true);
    await context.close();
  });

  test("a pulse travels along its edge, then is gone", async () => {
    const { page, context } = await open();
    const svg = 'section[data-sample="review-path"] svg';
    await page.locator('section[data-sample="review-path"]').scrollIntoViewIfNeeded();
    await page.waitForFunction((s) => document.querySelector(s)!.hasAttribute("data-play"), svg);
    let seen = new Set<string>();
    for (let i = 0; i < 40; i++) {
      const d = await page.evaluate((s) => {
        const p = [...document.querySelectorAll(`${s} .pulse`)].find((c) => Number(getComputedStyle(c).opacity) > 0.5);
        return p ? getComputedStyle(p).offsetDistance : "";
      }, svg);
      if (d) seen.add(d);
      await page.waitForTimeout(100);
    }
    expect(seen.size).toBeGreaterThan(3);
    await page.waitForTimeout(6000);
    expect(await page.evaluate((s) => [...document.querySelectorAll(`${s} .pulse`)].every((c) => Number(getComputedStyle(c).opacity) === 0), svg)).toBe(true);
    await context.close();
  });

  test("a reader who asks for reduced motion sees the whole figure, and nothing moves", async () => {
    const { page, context } = await open({ reducedMotion: "reduce" });
    const svg = 'section[data-sample="review-path"] svg';
    expect(await page.evaluate((s) => document.querySelector(s)!.hasAttribute("data-armed"), svg)).toBe(false);
    expect(await opacityOf(page, `${svg} g.node`)).toBe(1);
    await page.locator('section[data-sample="review-path"]').scrollIntoViewIfNeeded();
    await page.waitForTimeout(500);
    expect(await page.evaluate(() => document.getAnimations().filter((a) => /^av-/.test((a as CSSAnimation).animationName ?? "")).length)).toBe(0);
    await context.close();
  });

  test("hovering a node keeps its neighbours and edges in focus and quiets the rest", async () => {
    const { page, context } = await open({ reducedMotion: "no-preference" });
    const section = page.locator('section[data-sample="review-path"]');
    await section.scrollIntoViewIfNeeded();
    await page.waitForTimeout(5000);
    const review = section.locator('g.node[data-id="review"]');
    const box = (await review.boundingBox())!;
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.waitForTimeout(500);
    const opacity = (id: string) => section.locator(`g.node[data-id="${id}"]`).evaluate((e) => Number(getComputedStyle(e).opacity));
    expect(await opacity("review")).toBe(1);
    expect(await opacity("author")).toBe(1);
    expect(await opacity("log")).toBeLessThan(0.4);
    await page.mouse.move(2, 2);
    await page.waitForTimeout(500);
    expect(await opacity("log")).toBe(1);
    await context.close();
  });
});

describe("the zoom and pan viewer", () => {
  test("zooms by button and by key, fits, and scrolls to pan", async () => {
    const { page, context } = await open();
    const viewer = page.locator('section[data-sample="technical-big"] [role="group"]');
    await viewer.scrollIntoViewIfNeeded();
    const inner = viewer.locator('[role="region"] > div');
    const width = async () => (await inner.boundingBox())!.width;
    const start = await width();
    await viewer.getByRole("button", { name: "Zoom in" }).click();
    const zoomed = await width();
    expect(zoomed).toBeGreaterThan(start);
    await viewer.getByRole("button", { name: "Zoom out" }).click();
    await viewer.getByRole("button", { name: "Zoom out" }).click();
    expect(await width()).toBeLessThan(zoomed);
    await viewer.getByRole("button", { name: "100%" }).click();
    expect(await viewer.getByText("100%").first().isVisible()).toBe(true);
    const region = viewer.getByRole("region");
    await region.focus();
    await page.keyboard.press("+");
    expect(await width()).toBeGreaterThan(await inner.evaluate((e) => parseFloat((e as HTMLElement).style.width)) - 1);
    // At 150% the drawing is wider than its frame, so it scrolls.
    expect(await region.evaluate((e) => e.scrollWidth > e.clientWidth)).toBe(true);
    await region.evaluate((e) => (e.scrollLeft = 200));
    expect(await region.evaluate((e) => e.scrollLeft)).toBeGreaterThan(0);
    await context.close();
  });

  test("its controls are named buttons and its drawing is hidden from assistive technology", async () => {
    const { page, context } = await open();
    const viewer = page.locator('section[data-sample="technical-big"] [role="group"]');
    for (const name of ["Zoom in", "Zoom out", "Fit", "100%"]) expect(await viewer.getByRole("button", { name }).count()).toBe(1);
    expect(await viewer.locator("svg").first().evaluate((s) => s.closest('[aria-hidden="true"]') !== null)).toBe(true);
    await context.close();
  });
});

describe("theme and accessibility", () => {
  test("the same drawing follows the page's theme", async () => {
    const { page, context } = await open();
    const fill = () => page.locator('section[data-sample="static"] g.node text').first().evaluate((t) => getComputedStyle(t).fill);
    const light = await fill();
    await page.evaluate(() => document.documentElement.classList.add("dark"));
    expect(await fill()).not.toBe(light);
    await context.close();
  });

  test.each([false, true])("axe finds no violations in any figure (dark: %s)", async (dark) => {
    const { page, context } = await open({ dark });
    await page.addScriptTag({ content: axeSource });
    const violations = await page.evaluate(async () => {
      // @ts-expect-error injected
      const result = await window.axe.run(document.querySelector("main"), { runOnly: ["wcag2a", "wcag2aa", "wcag21aa", "best-practice"] });
      return result.violations.map((v: { id: string; nodes: { target: unknown }[] }) => `${v.id}: ${v.nodes.length} ${JSON.stringify(v.nodes[0]?.target)}`);
    });
    expect(violations).toEqual([]);
    await context.close();
  });
});
